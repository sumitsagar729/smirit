//! Desktop shell: wires the Smriti core into Tauri commands for the UI.

mod commands;
mod paths;

use smriti_core::Library;
use tauri::Manager;

pub struct AppState {
    pub library: Library,
}

/// Builds the typed command set; also used to export TypeScript bindings.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new().commands(tauri_specta::collect_commands![
        commands::app_info,
        commands::library_stats,
        commands::list_sources,
        commands::add_source,
        commands::remove_source,
    ])
}

/// Writes `src/lib/bindings.ts` (paths relative to the `src-tauri` crate).
pub fn export_bindings(builder: &tauri_specta::Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// @ts-nocheck\n// Generated by tauri-specta from the Rust commands. Do not edit."),
            concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/bindings.ts"),
        )
        .expect("failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let library_dir = paths::library_dir();
    let _log_guard = paths::init_logging(&library_dir);

    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let library = Library::open(&library_dir)?;
            app.manage(AppState { library });
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running Smriti");
}
