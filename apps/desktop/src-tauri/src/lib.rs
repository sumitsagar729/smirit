//! Desktop shell: wires the Smriti core into Tauri commands for the UI.

mod commands;
mod indexing;
mod paths;
mod protocol;

use std::sync::Arc;

use smriti_core::Library;
use tauri::{Manager, RunEvent};

pub struct AppState {
    pub library: Arc<Library>,
    pub indexer: indexing::Indexer,
}

/// Builds the typed command set; also used to export TypeScript bindings.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(tauri_specta::collect_commands![
            commands::app_info,
            commands::library_stats,
            commands::list_sources,
            commands::add_source,
            commands::remove_source,
            commands::rescan,
            commands::index_status,
            commands::timeline,
            commands::asset_detail,
            commands::people,
            commands::person,
            commands::face_groups,
            commands::group_faces,
            commands::person_faces,
            commands::asset_faces,
            commands::name_group,
            commands::assign_faces,
            commands::reject_faces,
            commands::ignore_faces,
            commands::ignore_group,
            commands::update_person,
            commands::merge_people,
            commands::delete_person,
            commands::set_cover_face,
        ])
        .typ::<indexing::IndexStatus>()
}

/// Writes `src/lib/bindings.ts` (paths relative to the `src-tauri` crate).
pub fn export_bindings(builder: &tauri_specta::Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// @ts-nocheck\n// Generated by tauri-specta from the Rust commands. Do not edit."),
            concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/bindings.ts"),
        )
        .expect("failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let library_dir = paths::library_dir();
    let _log_guard = paths::init_logging(&library_dir);

    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    let app = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(builder.invoke_handler())
        .register_asynchronous_uri_scheme_protocol("smriti", |ctx, req, responder| {
            let app = ctx.app_handle().clone();
            std::thread::spawn(move || responder.respond(protocol::handle(&app, req)));
        })
        .setup(move |app| {
            builder.mount_events(app);
            let library = Arc::new(Library::open(&library_dir)?);
            if library.models_dir().is_none() {
                let bundled = app.path().resource_dir().map(|d| d.join("models")).ok();
                // In development the models live in the repository.
                let dev = cfg!(debug_assertions)
                    .then(|| std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../models"));
                if !bundled.into_iter().chain(dev).any(|d| library.use_models(&d)) {
                    tracing::warn!("face models not found; people features are off");
                }
            }
            let indexer = indexing::Indexer::start(app.handle().clone(), library.clone());
            app.manage(AppState { library, indexer });
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("error while building Smriti");

    app.run(|app, event| {
        if let RunEvent::Exit = event
            && let Some(state) = app.try_state::<AppState>()
        {
            state.indexer.shutdown();
        }
    });
}
